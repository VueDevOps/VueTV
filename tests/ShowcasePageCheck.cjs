const {JSDOM, VirtualConsole} = require('../showcase/node_modules/jsdom');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../showcase/dist');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const errors = [];
const vc = new VirtualConsole();
vc.on('jsdomError', error => errors.push(error.message));
const dom = new JSDOM(html, {url:'http://localhost/',runScripts:'outside-only',pretendToBeVisual:true,virtualConsole:vc});
const w = dom.window;
w.matchMedia = () => ({matches:true});
w.IntersectionObserver = class {observe(element){element.classList.add('visible');} unobserve(){}};
w.Image = class {set src(value){this.complete=true;queueMicrotask(()=>this.onload?.());}};
w.HTMLDialogElement.prototype.showModal = function(){this.setAttribute('open','');};
w.HTMLDialogElement.prototype.close = function(){this.removeAttribute('open');this.dispatchEvent(new w.Event('close'));};
w.HTMLElement.prototype.scrollIntoView = function(){};
w.HTMLMediaElement.prototype.play = () => Promise.resolve();
w.HTMLMediaElement.prototype.pause = () => {};
w.eval(fs.readFileSync(path.join(root,'app.js'),'utf8'));
const $ = selector => w.document.querySelector(selector);
const settle = () => new Promise(resolve=>setTimeout(resolve,25));
(async()=>{
  await settle();
  for(const key of ['home','picks','apps','live','requests','profiles']) {
    $(`#tab-${key}`).click(); await settle();
    assert.equal($(`#tab-${key}`).getAttribute('aria-selected'),'true');
    assert.ok(fs.existsSync(path.join(root,$('#tour-image').getAttribute('src'))));
  }
  $('#tab-home').focus();
  $('#tab-home').dispatchEvent(new w.KeyboardEvent('keydown',{key:'ArrowDown',bubbles:true}));
  await settle();
  assert.equal(w.document.activeElement.id,'tab-picks');
  $('#remote-next').click(); await settle();
  assert.ok($('#tour-image').src.endsWith('goodfellas.webp'));
  $('#remote-open').focus(); $('#remote-open').click();
  assert.ok($('#media-dialog').open);
  assert.ok($('.dialog-image').src.endsWith('goodfellas.webp'));
  $('#media-dialog').dispatchEvent(new w.KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true}));
  assert.ok($('.dialog-image').src.endsWith('western.webp'));
  $('#close-dialog').click();
  assert.equal(w.document.activeElement.id,'remote-open');
  assert.equal(w.document.body.style.overflow,'');
  $('#avatar-compare').value='73'; $('#avatar-compare').dispatchEvent(new w.Event('input'));
  assert.equal($('#compare-after').style.clipPath,'inset(0 0 0 73%)');
  const stage = $('#compare-stage');
  let capture = null;
  stage.getBoundingClientRect = () => ({left:100,width:800});
  stage.setPointerCapture = id => {capture=id;};
  stage.hasPointerCapture = id => capture===id;
  stage.releasePointerCapture = () => {capture=null;};
  const pointer = (type,x) => {const event=new w.MouseEvent(type,{clientX:x,button:0,bubbles:true,cancelable:true});Object.defineProperties(event,{pointerId:{value:7},isPrimary:{value:true}});stage.dispatchEvent(event);return event;};
  assert.equal(pointer('pointerdown',300).defaultPrevented,true);
  pointer('pointermove',700);
  assert.equal($('#avatar-compare').value,'75');
  pointer('pointerup',1000);
  assert.equal($('#avatar-compare').value,'100');
  assert.equal(capture,null);
  pointer('pointermove',100);
  assert.equal($('#avatar-compare').value,'100');
  assert.ok([...stage.querySelectorAll('img')].every(img=>!img.draggable));
  $('[data-fact]').click(); assert.equal($('[data-fact]').getAttribute('aria-expanded'),'true');
  $('[data-video]').click(); assert.equal($('#cinematic-video').hidden,false); assert.equal($('#media-dialog').open,false); assert.equal($('#media-dialog video'),null);
  for(const match of html.matchAll(/(?:src|href)="([^"#]+)"/g)) {
    if(/^https?:/.test(match[1]))continue;
    assert.ok(fs.existsSync(path.join(root,match[1])),`Missing ${match[1]}`);
  }
  assert.deepEqual(errors,[]);
  console.log('PASS: six tour sections, next/keyboard navigation, gallery, focus restore, avatar slider, facts, video and local assets.');
  w.close();
})().catch(error=>{console.error(error);w.close();process.exitCode=1;});
